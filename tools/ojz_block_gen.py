#!/usr/bin/env python3
"""OJZ block-format data generator.

Converts existing column-strip data (generated by ojz_strip_gen.py) into
16x16 tile blocks with embedded dual-layer collision, independently S4LZ-compressed.

Usage:
    python3 tools/ojz_block_gen.py generate
    python3 tools/ojz_block_gen.py generate --no-cache   # force full recompute
    python3 tools/ojz_block_gen.py test

Caching: two content-addressed tiers (per-section result, per-block compression
memo) live under tools/.cache/. They are PURE memoization — the output is
byte-identical to --no-cache on the same tree. See the "Content-addressed
caches" block below for the key-completeness and integrity argument.

Input:  data/generated/ojz/act1/sec{N}_strips_a.bin (raw strip files)
Output: data/generated/ojz/act1/sec{N}_blocks.bin (block index + compressed blocks)

Each output file contains:
  - 256 × 4 bytes = 1024-byte block index table
    (each entry is a byte offset from file start; 0 = empty/air block;
    bit 31 set = RAW DIRECT — the offset points at an uncompressed 768-byte
    block inside the dictionary region)
  - Dictionary region: K raw blocks (768*K bytes), serving double duty as
    their own storage AND as the LZ window pre-seed for every compressed
    block in the section (K swept 0..3 per section, minimum total size)
  - Concatenated S4LZ-compressed blocks (compressed with the dict window)

Also emits data/generated/ojz/act1/sec_block_dicts.emp with per-section
OJZ_SEC{N}_BLOCK_DICT_LEN constants for the act descriptor (the dict region
always starts at blob+1024; only its length varies).

Raw block layout (768 bytes = BLOCK_RAW_SIZE):
  Bytes   0–511:  512 bytes nametable (16×16 × 2 bytes, row-major)
  Bytes 512–639:  128 bytes collision plane A (16 cols × 8 rows × 1 byte, row-major)
  Bytes 640–767:  128 bytes collision plane B (copy of plane A for OJZ)

Strip binary layout consumed here (STRIP_BYTE_SIZE bytes per column):
  Bytes 0 .. STRIP_NT_BYTES-1                 : nametable words (big-endian)
  Bytes STRIP_NT_BYTES .. +STRIP_COLL_ROWS-1  : collision plane A bytes
  Bytes +STRIP_COLL_ROWS .. +2*STRIP_COLL_ROWS-1 : collision plane B bytes
  Bytes +2*STRIP_COLL_ROWS .. end             : padding
"""

import hashlib
import multiprocessing
import pickle
import struct
import sys
import os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import s4lz

# Constants — must match constants.asm
SECTION_TILE_WIDTH = 256
SECTION_TILE_HEIGHT = 256
BLOCK_SIZE = 16
BLOCKS_PER_AXIS = SECTION_TILE_WIDTH // BLOCK_SIZE  # 16
BLOCKS_PER_SECTION = BLOCKS_PER_AXIS * BLOCKS_PER_AXIS  # 256
BLOCK_NT_SIZE = BLOCK_SIZE * BLOCK_SIZE * 2  # 512 bytes
BLOCK_COLL_COLS = BLOCK_SIZE  # 16 collision columns (1 per tile column)
BLOCK_COLL_ROWS = BLOCK_SIZE // 2  # 8 collision rows (16px cells)
BLOCK_COLL_PLANE_SIZE = BLOCK_COLL_COLS * BLOCK_COLL_ROWS  # 128 bytes per plane
BLOCK_COLL_SIZE = BLOCK_COLL_PLANE_SIZE * 2  # 256 bytes (plane A + plane B)
BLOCK_RAW_SIZE = BLOCK_NT_SIZE + BLOCK_COLL_SIZE  # 768 bytes

# Strip format (from ojz_strip_gen.py)
STRIP_TILE_HEIGHT = 256
STRIP_NT_BYTES = STRIP_TILE_HEIGHT * 2  # 512
STRIP_COLL_ROWS = STRIP_TILE_HEIGHT // 2  # 128 collision rows per plane
STRIP_COLL_OFFSET_A = STRIP_NT_BYTES          # 512: start of plane A collision
STRIP_COLL_OFFSET_B = STRIP_NT_BYTES + STRIP_COLL_ROWS  # 640: start of plane B collision
STRIP_PAD = 8
STRIP_BYTE_SIZE = STRIP_NT_BYTES + 2 * STRIP_COLL_ROWS + STRIP_PAD  # 776 bytes

BLOCK_INDEX_SIZE = BLOCKS_PER_SECTION * 4  # 1024 bytes
RAW_DIRECT_BIT = 0x80000000  # index entry bit 31: offset -> raw 768B block
MAX_DICT_BLOCKS = 3          # K sweep upper bound (sec_block_dict_len <= 3*768)

OUTPUT_DIR = os.path.join(
    os.path.dirname(__file__), "..", "games", "sonic4", "data", "generated", "ojz", "act1"
)

NUM_SECTIONS = 9
SECTION_IDS = list(range(NUM_SECTIONS))

# ---------------------------------------------------------------------------
# Content-addressed caches (pure memoization — NEVER changes output bytes)
# ---------------------------------------------------------------------------
#
# TWO tiers, because a one-chunk editor edit and a no-change re-bake are
# different problems:
#
#   TIER 1 — the per-SECTION result cache. Key = the raw strip input + both
#     module sources + the relevant constants. A no-change re-bake hits all 9
#     sections and costs ~0.15 s. It is useless the moment ANY byte of a
#     section changes, which is exactly the editor's loop.
#
#   TIER 2 — the per-BLOCK compression memo (the loop's cache). The K-sweep in
#     generate_section_blocks calls s4lz.compress once per (non-empty block,
#     dictionary) pair: ~282 calls per section at ~47 ms each = ~13 s, and that
#     was 99.7% of a real one-chunk re-bake (measured 2026-08-19: K-sweep
#     13.152 s of a 13.19 s section; parse+extract+rank together were 0.033 s).
#     A one-chunk edit dirties exactly ONE 16x16 block, so memoizing at the
#     (block, dict) granularity turns 282 compressions into 4.
#
# KEY COMPLETENESS (tier 2) — why a hit is provably a recompute:
#   s4lz.compress(data, tile_delta, dictionary) is a PURE, deterministic
#   function. s4lz.py imports only argparse/struct/sys; compress() reads no
#   file, no environment, no clock, no randomness, and holds no state across
#   calls. Its result is therefore a function of exactly:
#       (data, tile_delta, dictionary, the s4lz.py source itself)
#   and the tier-2 key hashes ALL FOUR — the full s4lz.py source bytes (which
#   subsumes "compressor version and flags": MAX_WINDOW, MIN_MATCH_WORDS,
#   VERSION_V3, the matcher, every constant), the tile_delta flag, and both
#   byte strings length-prefixed so no concatenation can alias. Nothing else
#   enters compress(), so there is no fourth input left to forget. Note the key
#   deliberately does NOT include ojz_block_gen.py's source: this generator only
#   BUILDS the two byte strings, and any change to how it builds them changes
#   the hashed bytes themselves. (Tier 1 does hash this file, because a tier-1
#   entry caches the whole section pipeline, layout and all.)
#
# INTEGRITY — two independent guards, because a cache that is merely trusted is
# the silent-wrong-data trap waiting to happen:
#   (a) FILE DIGEST. Both tiers store sha256(payload) beside the payload and
#       check it on load. Catches truncation and bit rot; a mismatch is a MISS
#       (recompute), never data. Writes go through os.replace, so an interrupted
#       run cannot leave a half-written entry in place either.
#   (b) OUTPUT VERIFICATION. Every accepted hit is DECODED and compared against
#       the source bytes it claims to encode — _verify_stream per block,
#       _verify_blob per section. This is what makes a hit provably equivalent
#       rather than key-trusted: even an entry forged with a valid file digest
#       cannot put wrong data in the ROM, because it would have to decode to the
#       right block, and if it does, it IS the right block. Verification is
#       affordable only because decompression is ~780x cheaper than compression
#       here (0.02 ms vs 19.1 ms per 768-byte block, measured): the whole check
#       costs ~2 ms per section against a 13 s sweep.
# The division of labour: the KEY guarantees byte-identity with --no-cache (a
# different-but-valid encoding would pass (b) yet occupy different bytes), and
# (a)+(b) guarantee correctness of the data even if the key were ever wrong.
# The escape hatch for any residual doubt is --no-cache, which reads and writes
# no cache at all.
#
# LOCATION — tools/.cache/ (already gitignored, line 118). Deliberately NOT
# inside games/sonic4/data/generated/: that tree is a COMMITTED artifact whose
# every file is checked by verify_level_bin.py's orphan pass, so cache files
# there would either trip the orphan check or leak into commits.
CACHE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         ".cache", "blockgen")
MEMO_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        ".cache", "blockmemo")
# Bound on retained tier-2 entries per section. A full sweep touches ~282; the
# surplus is history from earlier dictionary shapes, kept most-recent-first.
MEMO_MAX_ENTRIES = 4096
_THIS_FILE = os.path.abspath(__file__)
_S4LZ_FILE = os.path.abspath(s4lz.__file__)


def _read_source(path):
    with open(path, "rb") as f:
        return f.read()


_S4LZ_SOURCE_DIGEST = hashlib.sha256(_read_source(_S4LZ_FILE)).digest()


def _cache_key(section_idx, raw_data):
    """SHA-256 over the raw strip bytes + both module sources + constants.

    Hashing both module sources (not just inputs) guarantees the cache
    invalidates whenever the compressor or generator logic changes.
    """
    h = hashlib.sha256()
    h.update(b"ojz_block_gen.v1\0")
    h.update(struct.pack(">I", section_idx))
    h.update(struct.pack(">IIII", BLOCK_SIZE, MAX_DICT_BLOCKS,
                         BLOCK_RAW_SIZE, BLOCK_INDEX_SIZE))
    h.update(raw_data)
    h.update(_read_source(_THIS_FILE))
    h.update(_read_source(_S4LZ_FILE))
    return h.hexdigest()


def _digest_pack(payload):
    """Frame a payload with its sha256 so tampering/truncation reads as a miss."""
    return hashlib.sha256(payload).digest() + payload


def _digest_unpack(raw):
    """Return the payload if its stored digest matches, else None."""
    if len(raw) < 32:
        return None
    stored, payload = raw[:32], raw[32:]
    if hashlib.sha256(payload).digest() != stored:
        return None
    return payload


def _atomic_write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = f"{path}.tmp.{os.getpid()}"
    with open(tmp, "wb") as f:
        f.write(data)
    os.replace(tmp, path)


def _cache_load(key):
    """Return the cached (blob_bytes, dict_len, stats) tuple, or None on miss."""
    path = os.path.join(CACHE_DIR, key)
    try:
        with open(path, "rb") as f:
            raw = f.read()
    except OSError:
        return None
    payload = _digest_unpack(raw)
    if payload is None:
        return None
    try:
        return pickle.loads(payload)
    except Exception:
        return None


def _cache_store(key, result):
    """Persist the full (blob_bytes, dict_len, stats) tuple atomically."""
    payload = pickle.dumps(result, protocol=pickle.HIGHEST_PROTOCOL)
    _atomic_write(os.path.join(CACHE_DIR, key), _digest_pack(payload))


def _memo_path(section_idx):
    return os.path.join(MEMO_DIR, f"sec{section_idx}.memo")


def _memo_load(section_idx):
    """Load the tier-2 {key: compressed_stream} memo for one section."""
    try:
        with open(_memo_path(section_idx), "rb") as f:
            raw = f.read()
    except OSError:
        return {}
    payload = _digest_unpack(raw)
    if payload is None:
        return {}
    try:
        memo = pickle.loads(payload)
    except Exception:
        return {}
    return memo if isinstance(memo, dict) else {}


def _memo_store(section_idx, memo, used):
    """Write the memo back, entries touched THIS run first, then history.

    Insertion order carries the recency ranking, so the MEMO_MAX_ENTRIES trim
    always evicts the least recently useful keys.
    """
    ordered = {k: memo[k] for k in used if k in memo}
    for k, v in memo.items():
        if len(ordered) >= MEMO_MAX_ENTRIES:
            break
        if k not in ordered:
            ordered[k] = v
    payload = pickle.dumps(ordered, protocol=pickle.HIGHEST_PROTOCOL)
    _atomic_write(_memo_path(section_idx), _digest_pack(payload))


def _verify_stream(stream, data, dictionary):
    """True iff `stream` decodes back to `data` under `dictionary`.

    Every tier-2 HIT is checked this way before it is used. Decompression is
    ~780x cheaper than compression here (measured: 0.02 ms vs 19.1 ms per
    768-byte block), so the whole verification pass costs ~7 ms per section —
    it is free relative to the sweep it guards.

    What this proves, precisely: the served stream is a VALID encoding of this
    exact block under this exact dictionary, so no corrupted or forged entry
    can put wrong DATA in the ROM. It does not by itself prove the stream is
    the one compress() would emit (a different-but-valid encoding would decode
    the same while occupying a different number of bytes) — that is what the
    key does. Key completeness gives byte-identity with --no-cache; this check
    gives data correctness even when the key is trusted wrongly. Both, together,
    are the reason a hit needs no further justification.
    """
    try:
        return s4lz.decompress(stream, dictionary=dictionary) == data
    except Exception:
        return False


def _verify_blob(blob, dict_len, raw_blocks):
    """True iff a cached section blob decodes back to exactly `raw_blocks`.

    Same idea as _verify_stream, one tier up: every index entry is followed and
    every block decoded, so a tier-1 hit is checked against the source data
    rather than trusted on its key. Costs ~2 ms per section (decode is ~780x
    cheaper than the compression it replaces).
    """
    try:
        if len(blob) < BLOCK_INDEX_SIZE:
            return False
        for i, raw in enumerate(raw_blocks):
            decoded = decode_block(blob, dict_len, i)
            if decoded != raw:
                return False
        return True
    except Exception:
        return False


def _memo_key(data, dictionary, tile_delta=False):
    """Key for one s4lz.compress call — see KEY COMPLETENESS above."""
    h = hashlib.sha256()
    h.update(b"s4lz.compress.v1\0")
    h.update(_S4LZ_SOURCE_DIGEST)
    h.update(b"\x01" if tile_delta else b"\x00")
    h.update(struct.pack(">I", len(dictionary)))
    h.update(dictionary)
    h.update(struct.pack(">I", len(data)))
    h.update(data)
    return h.digest()


def load_raw_strips(section_idx):
    """Load raw (uncompressed) strip data for a section.

    Returns raw bytes — 128 bytes per column × 256 columns = 32768 bytes.
    """
    path = os.path.join(OUTPUT_DIR, f"sec{section_idx}_strips_a.bin")
    with open(path, "rb") as f:
        return f.read()


def parse_strips(raw_data):
    """Parse raw strip data into nametable grid + two collision grids.

    Returns:
        nametable:    2D list [row][col] of 16-bit tile words (256 rows × N cols)
        collision_a:  2D list [coll_row][col] of 8-bit collision bytes (128 rows × N cols), path A
        collision_b:  2D list [coll_row][col] of 8-bit collision bytes (128 rows × N cols), path B
    """
    num_cols = len(raw_data) // STRIP_BYTE_SIZE

    nametable = [[0] * num_cols for _ in range(STRIP_TILE_HEIGHT)]
    collision_a = [[0] * num_cols for _ in range(STRIP_COLL_ROWS)]
    collision_b = [[0] * num_cols for _ in range(STRIP_COLL_ROWS)]

    for col in range(num_cols):
        base = col * STRIP_BYTE_SIZE
        for row in range(STRIP_TILE_HEIGHT):
            word_off = base + row * 2
            nametable[row][col] = struct.unpack_from(">H", raw_data, word_off)[0]
        for cr in range(STRIP_COLL_ROWS):
            collision_a[cr][col] = raw_data[base + STRIP_COLL_OFFSET_A + cr]
            collision_b[cr][col] = raw_data[base + STRIP_COLL_OFFSET_B + cr]

    return nametable, collision_a, collision_b


def extract_block(nametable, collision_a, collision_b, block_x, block_y):
    """Extract one 16×16 block's data from the full section grids.

    Returns (nt_bytes, coll_a_bytes, coll_b_bytes):
        nt_bytes:      512 bytes — 16×16 tile words, row-major, big-endian
        coll_a_bytes:  128 bytes — 16 cols × 8 rows (path A), row-major
        coll_b_bytes:  128 bytes — 16 cols × 8 rows (path B), row-major
    """
    nt_data = bytearray(BLOCK_NT_SIZE)
    for row in range(BLOCK_SIZE):
        tile_row = block_y * BLOCK_SIZE + row
        for col in range(BLOCK_SIZE):
            tile_col = block_x * BLOCK_SIZE + col
            if tile_row < len(nametable) and tile_col < len(nametable[0]):
                word = nametable[tile_row][tile_col]
            else:
                word = 0
            offset = (row * BLOCK_SIZE + col) * 2
            struct.pack_into(">H", nt_data, offset, word)

    def extract_coll_plane(collision):
        coll_data = bytearray(BLOCK_COLL_PLANE_SIZE)
        for cr in range(BLOCK_COLL_ROWS):
            abs_coll_row = block_y * BLOCK_COLL_ROWS + cr
            for col in range(BLOCK_SIZE):
                tile_col = block_x * BLOCK_SIZE + col
                if abs_coll_row < len(collision) and tile_col < len(collision[0]):
                    byte = collision[abs_coll_row][tile_col]
                else:
                    byte = 0
                coll_data[cr * BLOCK_COLL_COLS + col] = byte
        return bytes(coll_data)

    return bytes(nt_data), extract_coll_plane(collision_a), extract_coll_plane(collision_b)


def select_dict_blocks(raw_blocks):
    """Rank non-empty blocks by 4-gram (word-pair) frequency coverage.

    Returns a list of block indices, best dictionary candidate first.
    A block's score is the sum, over its distinct 4-grams, of how many
    blocks in the section contain that gram — the block whose content is
    shared by the most other blocks scores highest.
    """
    blocks = [(i, b) for i, b in enumerate(raw_blocks) if b is not None]
    grams = {}
    gram_sets = {}
    for i, b in blocks:
        s = set(b[j:j + 4] for j in range(0, len(b) - 3, 2))
        gram_sets[i] = s
        for g in s:
            grams[g] = grams.get(g, 0) + 1
    scored = sorted(((sum(grams[g] for g in gram_sets[i]), -i) for i, _ in blocks),
                    reverse=True)
    return [-neg_i for _, neg_i in scored]


def generate_section_blocks(section_idx, use_cache=True):
    """Generate block index + dict region + compressed blocks for one section.

    Returns (blob_bytes, dict_len, stats) where blob_bytes is
    [1024-byte index table][raw dict blocks][compressed v3 streams],
    dict_len = bytes of raw dictionary (768 * K), and stats is a dict
    with 'k' and 'total' (bytes after the index table) plus the cache
    counters ('cached', 'memo_hits', 'memo_misses').
    Each block expands to BLOCK_RAW_SIZE (768) bytes:
      512B nametable + 128B collision plane A + 128B collision plane B.

    use_cache=False forces a full recompute through both cache tiers and
    writes nothing back — the `--no-cache` trust escape hatch.
    """
    raw_data = load_raw_strips(section_idx)

    # The block grid is rebuilt unconditionally — parse + extract + rank cost
    # 0.033 s per section against a 13 s sweep, and having the source blocks in
    # hand is what lets a TIER 1 hit be VERIFIED rather than merely trusted.
    nametable, collision_a, collision_b = parse_strips(raw_data)

    raw_blocks = []
    for block_y in range(BLOCKS_PER_AXIS):
        for block_x in range(BLOCKS_PER_AXIS):
            nt_data, coll_a_data, coll_b_data = extract_block(
                nametable, collision_a, collision_b, block_x, block_y
            )
            raw_block = nt_data + coll_a_data + coll_b_data
            raw_blocks.append(None if all(b == 0 for b in raw_block)
                              else raw_block)

    non_empty = [i for i, b in enumerate(raw_blocks) if b is not None]

    # TIER 1 — per-section result cache: skip the whole K-sweep when the inputs
    # and the generator/compressor sources are unchanged. The hit is accepted
    # only if the cached blob actually decodes back to these blocks.
    key = _cache_key(section_idx, raw_data)
    if use_cache:
        cached = _cache_load(key)
        if cached is not None:
            blob, dict_len, stats = cached
            if _verify_blob(blob, dict_len, raw_blocks):
                return blob, dict_len, dict(stats, cached=True,
                                            memo_hits=0, memo_misses=0,
                                            memo_rejected=0)

    ranking = select_dict_blocks(raw_blocks)

    # Sweep K = 0..MAX_DICT_BLOCKS dictionary blocks; pick minimum total.
    # Dict blocks are stored raw (768B each, their own storage) and every
    # other block is compressed with the dict as window pre-seed. The dict
    # is laid out best-block LAST so the highest-value content sits nearest
    # the data (smallest offsets -> most short-form matches).
    #
    # TIER 2 — the per-(block, dictionary) compression memo. This sweep is
    # ~99.7% of a section rebuild, and a one-chunk editor edit dirties exactly
    # one 16x16 block, so nearly every call below is a hit.
    memo = _memo_load(section_idx) if use_cache else {}
    memo_used = set()
    hits = misses = rejected = 0

    def compress_block(block_bytes, dict_bytes):
        nonlocal hits, misses, rejected
        if not use_cache:
            misses += 1
            return s4lz.compress(block_bytes, dictionary=dict_bytes)
        mk = _memo_key(block_bytes, dict_bytes)
        memo_used.add(mk)
        got = memo.get(mk)
        if got is not None and _verify_stream(got, block_bytes, dict_bytes):
            hits += 1
            return got
        if got is not None:
            # The entry was well-formed and its file digest checked out, but the
            # stream does not decode back to this block — drop it and recompute.
            rejected += 1
            del memo[mk]
        misses += 1
        got = s4lz.compress(block_bytes, dictionary=dict_bytes)
        memo[mk] = got
        return got

    best = None  # (total, k, dict_indices, dict_bytes, streams)
    for k in range(0, min(MAX_DICT_BLOCKS, len(non_empty)) + 1):
        dict_indices = ranking[:k]
        dict_bytes = b''.join(raw_blocks[i] for i in reversed(dict_indices))
        streams = {}
        total = k * BLOCK_RAW_SIZE
        for i in non_empty:
            if i in dict_indices:
                continue
            comp = compress_block(raw_blocks[i], dict_bytes)
            streams[i] = comp
            total += len(comp) + (len(comp) % 2)
        if best is None or total < best[0]:
            best = (total, k, dict_indices, dict_bytes, streams)

    if use_cache and misses:
        _memo_store(section_idx, memo, memo_used)

    total, k, dict_indices, dict_bytes, streams = best
    dict_len = len(dict_bytes)

    # Dict region position of each dict block (reversed layout, see above)
    dict_pos = {idx: j for j, idx in enumerate(reversed(dict_indices))}

    index_table = bytearray(BLOCK_INDEX_SIZE)
    block_data = bytearray(dict_bytes)

    for i, raw in enumerate(raw_blocks):
        if raw is None:
            struct.pack_into(">I", index_table, i * 4, 0)
        elif i in dict_pos:
            offset = BLOCK_INDEX_SIZE + dict_pos[i] * BLOCK_RAW_SIZE
            struct.pack_into(">I", index_table, i * 4, RAW_DIRECT_BIT | offset)
        else:
            offset = BLOCK_INDEX_SIZE + len(block_data)
            struct.pack_into(">I", index_table, i * 4, offset)
            block_data.extend(streams[i])
            if len(block_data) % 2:
                block_data.append(0)

    stats = {"k": k, "total": total}
    result = (bytes(index_table) + bytes(block_data), dict_len, stats)
    if use_cache:
        _cache_store(key, result)
    return (result[0], result[1],
            dict(stats, cached=False, memo_hits=hits, memo_misses=misses,
                 memo_rejected=rejected))


def generate_all(use_cache=True):
    """Generate block data for all OJZ sections."""
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    total_non_empty = 0
    total_blocks = 0
    dict_lens = []
    blob_owner = {}     # content hash -> first section index with that blob
    blob_lines = []     # generated include: BINCLUDE or equ alias per section
    dedup_saved = 0

    # Compress all sections in parallel — generate_section_blocks is pure and
    # independent per section. Pool.map preserves order, so the downstream dedup
    # and .asm emission see results in SECTION_IDS order exactly as a serial run.
    print(f"Compressing {NUM_SECTIONS} sections "
          f"({multiprocessing.cpu_count()} workers"
          + ("" if use_cache else ", CACHE DISABLED") + ")...", flush=True)
    with multiprocessing.Pool() as pool:
        results = pool.starmap(generate_section_blocks,
                               [(i, use_cache) for i in SECTION_IDS])

    sections_cached = 0
    sections_rebuilt = 0
    memo_hits = 0
    memo_misses = 0
    memo_rejected = 0

    for sec_idx, (output, dict_len, stats) in zip(SECTION_IDS, results):
        print(f"Section {sec_idx}...", end=" ", flush=True)
        dict_lens.append(dict_len)
        if stats.get("cached"):
            sections_cached += 1
        else:
            sections_rebuilt += 1
        memo_hits += stats.get("memo_hits", 0)
        memo_misses += stats.get("memo_misses", 0)
        memo_rejected += stats.get("memo_rejected", 0)

        index_data = output[:BLOCK_INDEX_SIZE]
        non_empty = sum(1 for i in range(BLOCKS_PER_SECTION)
                        if struct.unpack_from(">I", index_data, i * 4)[0] != 0)
        total_non_empty += non_empty
        total_blocks += BLOCKS_PER_SECTION

        out_path = os.path.join(OUTPUT_DIR, f"sec{sec_idx}_blocks.bin")
        with open(out_path, "wb") as f:
            f.write(output)

        # Content dedup: identical block blobs collapse to one BINCLUDE,
        # duplicate sections alias the owner's label (block staging is keyed
        # by section coordinates, not blob pointer, so sharing ROM is safe;
        # sec_block_dict = label + BLOCK_INDEX_SIZE also aliases correctly
        # since identical content implies identical dictionaries).
        digest = hashlib.sha256(output).hexdigest()
        owner = blob_owner.get(digest)
        if owner is None:
            blob_owner[digest] = sec_idx
            blob_lines.append(
                f'pub data OJZ_Sec{sec_idx}_Blocks = '
                f'embed("games/sonic4/data/generated/ojz/act1/sec{sec_idx}_blocks.bin")')
        else:
            blob_lines.append(
                f'pub equ  OJZ_Sec{sec_idx}_Blocks = extern("OJZ_Sec{owner}_Blocks")'
                f'   // content-dedup: identical to sec{owner}')
            dedup_saved += len(output)
        print(f"{len(output)} bytes (K={stats['k']} dict, "
              f"{non_empty}/{BLOCKS_PER_SECTION} non-empty blocks)"
              + (f" [deduped -> sec{owner}]" if owner is not None else ""))

    # Per-section dictionary lengths for the act descriptor (the dict region
    # always starts at blob + BLOCK_INDEX_SIZE; only the length varies). A
    # generated `.emp` const module (Parcel K3): comptime ints, zero ROM bytes,
    # consumed by act_descriptor.emp (the Sec.sec_block_dict_len field).
    dicts_path = os.path.join(OUTPUT_DIR, "sec_block_dicts.emp")
    with open(dicts_path, "w") as f:
        f.write("// AUTO-GENERATED by tools/ojz_block_gen.py — DO NOT EDIT.\n")
        f.write("// OJZ Act 1 per-section block-dictionary lengths. Dict region = K raw\n")
        f.write("// 768-byte blocks at sec{N}_blocks.bin + BLOCK_INDEX_SIZE; 0 = none.\n")
        f.write("// Consumed at comptime by act_descriptor.emp; emits ZERO ROM bytes.\n")
        f.write("module games.sonic4.ojz_block_dicts_act1\n\n")
        for sec_idx, dlen in zip(SECTION_IDS, dict_lens):
            f.write(f"pub const OJZ_SEC{sec_idx}_BLOCK_DICT_LEN = {dlen}\n")

    # Block blob embeds with dedup aliases — a natively-placed `.emp` section
    # (Parcel K3 run B); consumed by act_descriptor.emp. Identical blobs are
    # stored once; duplicate sections alias the owner via a zero-byte address equ.
    blobs_path = os.path.join(OUTPUT_DIR, "sec_block_blobs.emp")
    with open(blobs_path, "w") as f:
        f.write("// AUTO-GENERATED by tools/ojz_block_gen.py — DO NOT EDIT.\n")
        f.write("// OJZ Act 1 per-section 16x16 block blobs (S4LZ-compressed index +\n")
        f.write("// dict region, §4.7 2D). Identical blobs are stored ONCE; duplicate\n")
        f.write("// sections alias via a zero-byte address equ (content dedup). Consumed\n")
        f.write("// by act_descriptor.emp; natively placed at the sec_block_blobs section.\n")
        f.write("module games.sonic4.ojz_sec_block_blobs_act1 in sec_block_blobs\n\n")
        f.write("\n".join(blob_lines) + "\n")

    print(f"\nDone. {total_non_empty}/{total_blocks} total non-empty blocks "
          f"across {NUM_SECTIONS} sections; blob dedup saved "
          f"{dedup_saved} ROM bytes.")
    if use_cache:
        print(f"Cache: {sections_cached}/{NUM_SECTIONS} sections served whole, "
              f"{sections_rebuilt} rebuilt; block compressions "
              f"{memo_hits} hit / {memo_misses} recomputed"
              + (f"; {memo_rejected} CACHE ENTRIES REJECTED by the decode check"
                 if memo_rejected else "") + ".")
    else:
        print(f"Cache: DISABLED (--no-cache) — {sections_rebuilt} sections and "
              f"{memo_misses} block compressions recomputed from scratch.")


